"""Phase 3 dev acquisition: focused captures of the 137 thesis variants and their clean twins (free, no LLM).

  python -m eval.dev_acquire                 # all apps
  python -m eval.dev_acquire --app checkout --profiles checkout-co-sem-052

Checkout: the student's focused runner (`scripts/benchmarks/checkout/runner.py`) is called in-process once per
seeded profile ("seeded"), and once more with the same profile's capture path but the clean profile injected into
the page ("clean"). The clean twin shows the same states without the seed, so the case's element there is a
no-violation control. A twin whose capture fails (the runner asserts seeded behaviour on some paths) is logged and
left out.

Booking: the student's integration tests already capture each case clean and seeded; they are run with pytest
`--basetemp`, and the kept run directories are copied.

Run directories go to `runs/w4a-dev/` (ignored by git; regenerated by this script). The log goes to
`results/dev/acquisition.jsonl`.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
  sys.path.insert(0, str(ROOT))

RUNS = ROOT / "runs" / "w4a-dev"
RESULTS = ROOT / "results" / "dev"
REGISTRY = ROOT / "benchmarks" / "registry" / "benchmark-case-registry.json"
CHECKOUT_CLEAN = "checkout-clean-v1"
OUTPUT_DIRS = ("candidates", "confirmations", "evaluation", "reports")


def profiles(app: str) -> list[dict]:
  from src.analysis.evaluation.benchmark_registry import load_benchmark_registry
  configurations = load_benchmark_registry(REGISTRY)["seeded_configurations"]
  return [c for c in configurations if c.get("app") == app and c.get("seed_ids")]


def _log(record: dict) -> None:
  RESULTS.mkdir(parents=True, exist_ok=True)
  with (RESULTS / "acquisition.jsonl").open("a", encoding="utf-8") as stream:
    stream.write(json.dumps(record, ensure_ascii=False) + "\n")


class _InjectProfile:
  """Wraps the runner's async_playwright so the page gets `inject` instead of the runner's profile."""

  def __init__(self, runner, inject: str):
    self.runner, self.inject = runner, inject
    from playwright.async_api import async_playwright
    self._real = async_playwright

  def __call__(self):
    outer = self

    class _Manager:
      async def __aenter__(self):
        self._cm = outer._real()
        playwright = await self._cm.__aenter__()
        launch = playwright.chromium.launch

        async def patched_launch(*args, **kwargs):
          browser = await launch(*args, **kwargs)
          new_context = browser.new_context

          async def patched_new_context(*a, **k):
            context = await new_context(*a, **k)
            add_init_script = context.add_init_script

            async def patched_add_init_script(script=None, **kw):
              if isinstance(script, str) and outer.runner.CHECKOUT_PROFILE_GLOBAL in script:
                script = f"window[{json.dumps(outer.runner.CHECKOUT_PROFILE_GLOBAL)}] = {json.dumps(outer.inject)};"
              return await add_init_script(script, **kw)

            context.add_init_script = patched_add_init_script
            return context

          browser.new_context = patched_new_context
          return browser

        playwright.chromium.launch = patched_launch
        return playwright

      async def __aexit__(self, *exc):
        return await self._cm.__aexit__(*exc)

    return _Manager()


def acquire_checkout(selected: set[str] | None = None, build: bool = False) -> None:
  import scripts.benchmarks.checkout.runner as runner
  from scripts.benchmarks.checkout import spa_process

  configurations = [c for c in profiles("checkout-flow") if not selected or c["configuration_id"] in selected]
  if build:
    spa_process.build_checkout_app()
  support = spa_process.start_controlled_support_server()
  spa_process.wait_for_url(spa_process.CONTROLLED_SUPPORT_RETURNS_URL, timeout_seconds=20)
  port = spa_process.find_free_port()
  preview = spa_process.start_vite_preview(port=port)
  base_url = f"http://127.0.0.1:{port}"
  real_playwright = runner.async_playwright
  try:
    spa_process.wait_for_url(f"{base_url}/products", timeout_seconds=20)
    for configuration in configurations:
      profile = configuration["configuration_id"]
      support_capture = bool(spa_process.requires_controlled_support_destination(profile))
      for kind in ("seeded", "clean"):
        run_dir = RUNS / "checkout" / profile / kind
        if (run_dir / "run_metadata.json").exists():
          continue
        if run_dir.exists():
          shutil.rmtree(run_dir)
        runner.async_playwright = real_playwright if kind == "seeded" else _InjectProfile(runner, CHECKOUT_CLEAN)
        started = time.perf_counter()
        error = None
        try:
          asyncio.run(runner._run_capture(base_url=base_url, run_dir=run_dir, profile=profile,
                                          capture_controlled_support_destination=support_capture))
        except Exception as exc:  # the runner asserts seeded behaviour on some paths
          error = f"{type(exc).__name__}: {str(exc)[:300]}"
          shutil.rmtree(run_dir, ignore_errors=True)
        finally:
          runner.async_playwright = real_playwright
        _log({"app": "checkout-flow", "profile": profile, "seed_ids": configuration["seed_ids"], "kind": kind,
              "run_dir": str(run_dir.relative_to(ROOT)), "ok": error is None, "error": error,
              "seconds": round(time.perf_counter() - started, 1)})
        print(profile, kind, "ok" if error is None else error, flush=True)
  finally:
    spa_process.stop_process(preview)
    spa_process.stop_process(support)


def acquire_booking(selected: set[str] | None = None) -> None:
  base = RUNS / "booking" / "pytest"
  if base.exists():
    shutil.rmtree(base)
  base.parent.mkdir(parents=True, exist_ok=True)  # pytest creates --basetemp but not its parents
  wanted = {c["configuration_id"] for c in profiles("booking-scheduler")}
  if selected:
    wanted &= selected
  numbers = sorted(re.search(r"(\d+)$", p).group(1) for p in wanted)
  keyword = " or ".join(f"bs_sem_{n}" for n in numbers)
  started = time.perf_counter()
  completed = subprocess.run([sys.executable, "-m", "pytest", "tests/test_booking_accessgraph_integration.py", "-q",
                              "-k", keyword, f"--basetemp={base}", "-p", "no:cacheprovider"],
                             cwd=ROOT, capture_output=True, text=True)
  tail = completed.stdout.strip().splitlines()[-1:] if completed.stdout else []
  print("booking pytest:", tail, flush=True)
  for metadata in sorted(base.rglob("run_metadata.json")):
    source = metadata.parent
    match = re.search(r"bs_sem_(\d+)", str(source.relative_to(base)))
    label = source.name
    if not match or label not in ("clean", "seeded"):
      continue
    profile = f"booking-bs-sem-{match.group(1)}"
    if profile not in wanted:
      continue
    target = RUNS / "booking" / profile / label
    if target.exists():
      continue
    shutil.copytree(source, target, ignore=shutil.ignore_patterns(*OUTPUT_DIRS))
    _log({"app": "booking-scheduler", "profile": profile, "seed_ids": [f"bs-sem-{match.group(1)}"], "kind": label,
          "run_dir": str(target.relative_to(ROOT)), "ok": True, "error": None,
          "source_test": str(source.relative_to(base))})
  _log({"app": "booking-scheduler", "event": "pytest", "returncode": completed.returncode, "summary": tail,
        "seconds": round(time.perf_counter() - started, 1)})


def main(argv: list[str] | None = None) -> int:
  parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  parser.add_argument("--app", choices=("checkout", "booking", "all"), default="all")
  parser.add_argument("--profiles", nargs="*", default=None)
  parser.add_argument("--build", action="store_true", help="rebuild the Checkout dist first")
  args = parser.parse_args(argv)
  selected = set(args.profiles) if args.profiles else None
  if args.app in ("checkout", "all"):
    acquire_checkout(selected, build=args.build)
  if args.app in ("booking", "all"):
    acquire_booking(selected)
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
