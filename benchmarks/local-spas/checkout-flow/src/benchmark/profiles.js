export function getActiveSeeds(profileId = getConfiguredProfileId()) {
  const configuredSeedIds = CHECKOUT_PROFILES[profileId] ?? [];
  return configuredSeedIds.filter((seedId) =>
    CHECKOUT_BENCHMARK_SEED_IDS.includes(seedId),
  );
}

export function hasActiveSeed(activeSeeds, seedId) {
  return activeSeeds.includes(seedId);
}

function getConfiguredProfileId() {
  if (
    typeof window === "undefined" ||
    typeof window[CHECKOUT_PROFILE_GLOBAL] !== "string"
  ) {
    return "";
  }

  return window[CHECKOUT_PROFILE_GLOBAL];
}
